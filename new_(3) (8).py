    occlusion_mask = (~face_mask).astype(np.uint8) * 255

    # Step C: Inpainting
    # This fills in the "non-face" areas using surrounding face texture
    inpainted = cv2.inpaint(img_bgr, occlusion_mask, 3, cv2.INPAINT_TELEA)

    # Save Result
    cv2.imwrite(os.path.join(OUTPUT_DIR, img_name), inpainted)

