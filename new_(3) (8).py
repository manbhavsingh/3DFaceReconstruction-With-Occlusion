def compute_nme(v1, v2):
    errors = np.linalg.norm(v1 - v2, axis=1)

    bbox_min = np.min(v1, axis=0)
    bbox_max = np.max(v1, axis=0)
    diag = np.linalg.norm(bbox_max - bbox_min)

    if diag == 0:
        return np.nan

    return np.mean(errors) / diag


# -----------------------------
# Main Comparison Function
# -----------------------------
def compare_results(name):
    res = {'Filename': name}

    orig_obj = os.path.join(PATH_ORIG, f"{name}.obj")
    inpaint_obj = os.path.join(PATH_INPAINT, f"{name}.obj")
    orig_mat = os.path.join(PATH_ORIG, f"{name}.mat")
    inpaint_mat = os.path.join(PATH_INPAINT, f"{name}.mat")

    # --- Mesh Metrics ---
    if os.path.exists(orig_obj) and os.path.exists(inpaint_obj):
        m1 = trimesh.load(orig_obj)
        m2 = trimesh.load(inpaint_obj)

        v1, v2 = m1.vertices, m2.vertices

        # Sanity check
        if v1.shape != v2.shape:
            print(f"[WARNING] Shape mismatch in {name}")
            res['Mesh_RMSE'] = np.nan
            res['NME'] = np.nan
        else:
            dist = np.linalg.norm(v1 - v2, axis=1)

            # RMSE
            res['Mesh_RMSE'] = np.sqrt(np.mean(dist**2))

            # NME
            res['NME'] = compute_nme(v1, v2)

    # --- Parameter Similarity ---
    if os.path.exists(orig_mat) and os.path.exists(inpaint_mat):
        mat1 = loadmat(orig_mat)
        mat2 = loadmat(inpaint_mat)

        for key in ['id', 'exp']:
            if key in mat1 and key in mat2:
                v1 = mat1[key].flatten()
                v2 = mat2[key].flatten()

                denom = (np.linalg.norm(v1) * np.linalg.norm(v2))
                if denom == 0:
                    sim = np.nan
                else:
                    sim = np.dot(v1, v2) / denom

                res[f'{key}_Similarity'] = sim

    return res


