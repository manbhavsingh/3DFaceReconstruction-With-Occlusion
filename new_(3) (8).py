def safe_cosine_similarity(v1, v2):
    """Numerically stable cosine similarity"""
    v1 = v1.flatten()
    v2 = v2.flatten()

    denom = (np.linalg.norm(v1) * np.linalg.norm(v2))
    if denom < 1e-8:
        return 0.0

    return float(np.dot(v1, v2) / denom)


def compute_chamfer_distance(points1, points2):
    """Symmetric Chamfer Distance"""
    tree1 = cKDTree(points1)
    tree2 = cKDTree(points2)

    dist1, _ = tree1.query(points2)
    dist2, _ = tree2.query(points1)

    chamfer = np.mean(dist1**2) + np.mean(dist2**2)
    return chamfer


